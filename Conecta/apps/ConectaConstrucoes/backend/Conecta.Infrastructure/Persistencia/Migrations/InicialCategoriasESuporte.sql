CREATE TABLE categorias (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    nome character varying(100) NOT NULL,
    slug character varying(100) NOT NULL,
    descricao character varying(5000),
    icone_url character varying(255),
    ativo boolean NOT NULL DEFAULT TRUE,
    criado_em timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    atualizado_em timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_categorias" PRIMARY KEY (id),
    CONSTRAINT ck_categorias_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

CREATE TABLE usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    email character varying(255) NOT NULL,
    senha_hash character varying(255) NOT NULL,
    perfil character varying(20) NOT NULL,
    ativo boolean DEFAULT TRUE,
    documento character varying(20),
    verificado boolean DEFAULT FALSE,
    foto_perfil_url character varying(255),
    media_avaliacao numeric(3,2) DEFAULT 0.0,
    total_avaliacoes integer DEFAULT 0,
    termos_aceitos_em timestamp with time zone,
    data_criacao timestamp with time zone DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_usuarios" PRIMARY KEY (id)
);

CREATE TABLE prestadores (
    usuario_id integer NOT NULL,
    nome_fantasia character varying(100) NOT NULL,
    bio text,
    plano_assinatura character(1) NOT NULL DEFAULT 'G',
    status_disponibilidade character varying(20) NOT NULL DEFAULT 'DISPONIVEL',
    CONSTRAINT "PK_prestadores" PRIMARY KEY (usuario_id),
    CONSTRAINT "FK_prestadores_usuarios_usuario_id" FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT
);

CREATE TABLE prestador_categorias (
    prestador_id integer NOT NULL,
    categoria_id integer NOT NULL,
    adicionado_em timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_prestador_categorias" PRIMARY KEY (prestador_id, categoria_id),
    CONSTRAINT "FK_prestador_categorias_categorias_categoria_id" FOREIGN KEY (categoria_id) REFERENCES categorias (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_prestador_categorias_prestadores_prestador_id" FOREIGN KEY (prestador_id) REFERENCES prestadores (usuario_id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_categorias_slug ON categorias (slug);

